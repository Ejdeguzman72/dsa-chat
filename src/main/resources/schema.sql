-- =====================================================
-- DSA CHAT DATABASE SCHEMA
-- PostgreSQL
-- =====================================================

-- =====================================================
-- DSA USER
-- =====================================================

CREATE TABLE IF NOT EXISTS public.dsa_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creation_date DATE NULL,
    description VARCHAR(255) NULL,
    email VARCHAR(255) NULL,
    firstname VARCHAR(255) NULL,
    interests VARCHAR[] NULL,
    last_updatetime DATE NULL,
    lastname VARCHAR(255) NULL,
    password VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    role_id BIGINT NOT NULL DEFAULT 1,

    CONSTRAINT uk_dsa_user_username
        UNIQUE (username),

    CONSTRAINT fk_role_user
        FOREIGN KEY (role_id)
        REFERENCES public.role(role_id)
);

-- =====================================================
-- ROLE
-- =====================================================

CREATE TABLE IF NOT EXISTS public."role" (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role VARCHAR(255) NULL
);

-- =====================================================
-- CHAT MESSAGE
-- =====================================================

CREATE TABLE IF NOT EXISTS public.chat_message (
    chat_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(255) NULL,
    sent_datetime TIMESTAMP(6) NULL,
    user_id BIGINT NULL,

    CONSTRAINT fk_chat_message_user
        FOREIGN KEY (user_id)
        REFERENCES public.dsa_user(user_id)
);

-- =====================================================
-- DSA EVENT
-- =====================================================

CREATE TABLE IF NOT EXISTS public.dsa_event (
    event_id UUID NOT NULL PRIMARY KEY,
    event_name VARCHAR(255) NULL,
    event_date DATE NULL,
    event_type VARCHAR(255) NULL,
    description VARCHAR(255) NULL,
    create_time DATE NULL,
    last_updatetime DATE NULL
);

-- =====================================================
-- ANNOUNCEMENT
-- =====================================================

CREATE TABLE IF NOT EXISTS public.announcement (
    announcement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(255) NULL,
    sent_datetime TIMESTAMP(6) NULL,
    create_datetime TIMESTAMP(6) NULL,
    last_updatedatetime TIMESTAMP(6) NULL
);

-- =====================================================
-- PASSWORD RESET TOKENS
-- =====================================================

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    token_id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES dsa_user(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =====================================================
-- EVENT_ATTENDEE
-- =====================================================

CREATE TABLE IF NOT EXISTS event_attendee (
    event_id UUID NOT NULL,
    user_id BIGINT NOT NULL,

    attendance_status VARCHAR(20) NOT NULL
        DEFAULT 'PENDING',

    responded_at TIMESTAMP,

    CONSTRAINT pk_event_attendee
        PRIMARY KEY (event_id, user_id),

    CONSTRAINT fk_event_attendee_event
        FOREIGN KEY (event_id)
        REFERENCES dsa_event(event_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_event_attendee_user
        FOREIGN KEY (user_id)
        REFERENCES dsa_user(user_id)
        ON DELETE CASCADE
);